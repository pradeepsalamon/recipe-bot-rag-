# ─── Cost estimation ───
# Gemini 2.0 Flash pricing (approximate, per 1M tokens)
COST_PER_1M_INPUT = 0.10    # $0.10 per 1M input tokens
COST_PER_1M_OUTPUT = 0.40   # $0.40 per 1M output tokens
# Simplified: use blended rate per total token
COST_PER_TOKEN = 0.15 / 1_000_000  # ~$0.15 per 1M tokens blended


def compute_metrics(results: list, arm_name: str) -> dict:
    """Compute pass rate, p50/p99 latency, total tokens, cost per question."""
    verdicts = [r["verdict"] for r in results]
    latencies = [r["latency_ms"] for r in results if r["latency_ms"] > 0]
    total_tokens = sum(r["total_tokens"] for r in results)
    n_cases = len(results)

    pass_count = sum(1 for v in verdicts if v == "Pass")
    pass_rate = pass_count / n_cases * 100

    if latencies:
        p50 = statistics.median(latencies)
        sorted_lat = sorted(latencies)
        p99_idx = max(0, int(len(sorted_lat) * 0.99) - 1)
        p99 = sorted_lat[p99_idx] if sorted_lat else 0
    else:
        p50 = 0
        p99 = 0

    cost_total = total_tokens * COST_PER_TOKEN
    cost_per_question = cost_total / n_cases if n_cases > 0 else 0

    return {
        "arm": arm_name,
        "pass_rate": f"{pass_rate:.0f}% ({pass_count}/{n_cases})",
        "pass_rate_pct": pass_rate,
        "p50_latency_ms": round(p50, 1),
        "p99_latency_ms": round(p99, 1),
        "total_tokens": total_tokens,
        "cost_per_question": round(cost_per_question * 100, 4),  # in cents
        "cost_total_cents": round(cost_total * 100, 4),
        "n_cases": n_cases,
    }


