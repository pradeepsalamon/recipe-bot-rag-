def main():
    log("=" * 70)
    log("  RACE: Single Agent vs Multi-Agent Orchestrator")
    log("  10 Week-6 Eval Cases -- Same Judge, Same Inputs")
    log("=" * 70)
    log()

    # Load eval cases
    cases_path = os.path.join(os.path.dirname(__file__), "eval_cases_10.json")
    with open(cases_path) as f:
        cases = json.load(f)
    log(f"Loaded {len(cases)} eval cases from Week 6.\n")

    # --- ARM 1: Single Agent ---
    log("-" * 40)
    log("ARM 1: Single Agent")
    log("-" * 40)
    single_results = run_all_single_agent(cases)
    for r in single_results:
        log(f"  {r['case_id']}: {r['verdict']:<5} | tok={r['total_tokens']:>5} | lat={r['latency_ms']:>8.1f}ms")
    log()

    # --- ARM 2: Multi-Agent Orchestrator ---
    log("-" * 40)
    log("ARM 2: Multi-Agent Orchestrator")
    log("-" * 40)
    multi_results = run_all_multi_agent(cases)
    for r in multi_results:
        inj = " <- FAILURE INJECTED" if r.get("failure_injected") else ""
        bhv = f" -> {r['orchestrator_behaviour']}" if r.get("orchestrator_behaviour") else ""
        log(f"  {r['case_id']}: {r['verdict']:<5} | tok={r['total_tokens']:>5} | lat={r['latency_ms']:>8.1f}ms{inj}{bhv}")
    log()

    # --- Compute Metrics ---
    single_metrics = compute_metrics(single_results, "Single Agent")
    multi_metrics = compute_metrics(multi_results, "Multi-Agent Orchestrator")

    log("-" * 40)
    log("METRICS SUMMARY")
    log("-" * 40)
    log(f"{'Metric':<25} {'Single':>15} {'Multi':>15}")
    log(f"{'Pass Rate':<25} {single_metrics['pass_rate']:>15} {multi_metrics['pass_rate']:>15}")
    log(f"{'p50 Latency (ms)':<25} {single_metrics['p50_latency_ms']:>15.1f} {multi_metrics['p50_latency_ms']:>15.1f}")
    log(f"{'p99 Latency (ms)':<25} {single_metrics['p99_latency_ms']:>15.1f} {multi_metrics['p99_latency_ms']:>15.1f}")
    log(f"{'Total Tokens':<25} {single_metrics['total_tokens']:>15,} {multi_metrics['total_tokens']:>15,}")
    log(f"{'Cost/Question (cents)':<25} {single_metrics['cost_per_question']:>15.4f} {multi_metrics['cost_per_question']:>15.4f}")
    log()

    # --- Multiplier ---
    multiplier_line = compute_multiplier_and_attribution(
        single_metrics["total_tokens"],
        multi_metrics["total_tokens"],
        handoff_log,
    )
    log("-" * 40)
    log("CONTEXT RE-SEND MULTIPLIER")
    log("-" * 40)
    log(multiplier_line)
    log()

    # --- Generate All Deliverables ---
    out_dir = os.path.dirname(os.path.abspath(__file__))

    # 1. race_table.md
    race_md = generate_race_table(single_metrics, multi_metrics)
    # Append case details
    case_lines = []
    for c in cases:
        case_lines.append(
            f"| {c['id']} | {c['input_recipe']} | {c['requested_substitution']} | {c['mode']} |"
        )
    race_md += "\n".join(case_lines)
    race_md += "\n\n" + multiplier_line + "\n"

    with open(os.path.join(out_dir, "race_table.md"), "w", encoding="utf-8") as f:
        f.write(race_md)
    log("[OK] race_table.md written")

    # 2. handoffs.log
    handoffs_content = generate_handoffs_log(handoff_log)
    with open(os.path.join(out_dir, "handoffs.log"), "w", encoding="utf-8") as f:
        f.write(handoffs_content)
    log("[OK] handoffs.log written")

    # 3. failure_case.md
    failure_md = generate_failure_case(multi_results, INJECT_FAILURE_CASE)
    with open(os.path.join(out_dir, "failure_case.md"), "w", encoding="utf-8") as f:
        f.write(failure_md)
    log("[OK] failure_case.md written")

    # 4. verdict.md
    verdict_md = generate_verdict(single_metrics, multi_metrics, multiplier_line)
    with open(os.path.join(out_dir, "verdict.md"), "w", encoding="utf-8") as f:
        f.write(verdict_md)
    log("[OK] verdict.md written")

    # 5. Bonus: agent_card.md
    agent_card_md = generate_agent_card()
    with open(os.path.join(out_dir, "agent_card.md"), "w", encoding="utf-8") as f:
        f.write(agent_card_md)
    log("[OK] agent_card.md written (bonus)")

    # 6. Save raw results
    with open(os.path.join(out_dir, "single_agent_results.json"), "w", encoding="utf-8") as f:
        json.dump(single_results, f, indent=2)
    with open(os.path.join(out_dir, "multi_agent_results.json"), "w", encoding="utf-8") as f:
        json.dump(multi_results, f, indent=2, default=str)
    with open(os.path.join(out_dir, "handoff_log_raw.json"), "w", encoding="utf-8") as f:
        json.dump(handoff_log, f, indent=2)
    log("[OK] Raw result JSONs saved")

    log()
    log("=" * 70)
    log("  ALL DELIVERABLES GENERATED SUCCESSFULLY")
    log("=" * 70)
    log()
    log("Submission checklist:")
    log("  [OK] race_table.md     -- 4 metrics x 2 arms, same 10 cases named")
    log("  [OK] handoffs.log      -- every hand-off with its token count")
    log("  [OK] Multiplier line   -- multi/single tokens to 1 decimal, dominant hand-off named")
    log("  [OK] failure_case.md   -- the injected 500 and what the orchestrator actually did")
    log("  [OK] verdict.md        -- keep/kill, two numbers cited, sunk-cost named")
    log("  [OK] agent_card.md     -- A2A AgentCard + task lifecycle (bonus)")


if __name__ == "__main__":
    main()

